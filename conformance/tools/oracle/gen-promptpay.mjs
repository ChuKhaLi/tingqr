// Generate PromptPay encode vectors with thai-qr-payment@1.2.0 (uunw, MIT), whose builder writes tags in ascending
// order like tingqr (00, 01, 29/30, 53, 54, 58, 63). Every payload is then read back with promptparse@1.7.1
// (maythiwat, MIT), an independent parser: each field `expected` names must equal what promptparse reads, or the
// script stops. `expected` is built from the case inputs, never from tingqr.
//
// Run: cd conformance/tools/oracle && pnpm install && node gen-promptpay.mjs
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'promptparse'

const require = createRequire(import.meta.url)
const { ThaiQRPaymentBuilder } = require('thai-qr-payment')

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'vectors', 'promptpay')

const CASES = [
  { id: 'promptpay-encode-mobile', build: (b) => b.promptpay('0812223333'), input: { target: { mobile: '0812223333' } } },
  {
    id: 'promptpay-encode-mobile-amount',
    build: (b) => b.promptpay('0812223333').amount(30),
    input: { target: { mobile: '0812223333' }, amount: 30 },
  },
  {
    id: 'promptpay-encode-national-id',
    build: (b) => b.promptpay('1111111111111'),
    input: { target: { nationalId: '1111111111111' } },
  },
  {
    id: 'promptpay-encode-ewallet',
    build: (b) => b.promptpay('012345678901234'),
    input: { target: { eWallet: '012345678901234' } },
  },
  {
    id: 'promptpay-encode-bill',
    build: (b) =>
      b.billPayment({ billerId: '099400016550100', reference1: '123456789012', reference2: '670429' }).amount(3649.22),
    input: {
      target: { billerId: '099400016550100', reference1: '123456789012', reference2: '670429' },
      amount: '3649.22',
    },
  },
]

function amountText(amount) {
  return amount === undefined ? undefined : Number(amount).toFixed(2)
}

function expectedFor({ target, amount }) {
  const common = { initiation: amount === undefined ? 'static' : 'dynamic', currency: '764', country: 'TH' }
  if (amount !== undefined) common.amount = amountText(amount)
  if (target.billerId) {
    const subFields = { '01': target.billerId }
    const e = { kind: 'bill-payment', crossBorder: false, billerId: target.billerId }
    if (target.reference1) e.reference1 = subFields['02'] = target.reference1
    if (target.reference2) e.reference2 = subFields['03'] = target.reference2
    return { ...e, subFields, ...common }
  }
  const [proxyType, sub, proxy] = target.mobile
    ? ['mobile', '01', '0066' + target.mobile.slice(1)]
    : target.nationalId
      ? ['nationalId', '02', target.nationalId]
      : ['eWallet', '03', target.eWallet]
  const e = { kind: 'credit-transfer', ota: false, proxyType, proxy, subFields: { [sub]: proxy }, ...common }
  if (target.mobile) e.mobile = target.mobile
  return e
}

function verify(id, payload, e) {
  const qr = parse(payload, true)
  if (!qr) throw new Error(`${id}: promptparse rejects ${payload}`)
  const tag = e.kind === 'credit-transfer' ? '29' : '30'
  const pairs = [
    [qr.getTagValue('01'), e.initiation === 'dynamic' ? '12' : '11'],
    [qr.getTagValue(tag, '00'), tag === '29' ? 'A000000677010111' : 'A000000677010112'],
    [qr.getTagValue('53'), e.currency],
    [qr.getTagValue('54'), e.amount],
    [qr.getTagValue('58'), e.country],
    ...Object.entries(e.subFields).map(([sub, value]) => [qr.getTagValue(tag, sub), value]),
    [qr.getTags().map((t) => t.id).join(','), ['00', '01', tag, '53', ...(e.amount ? ['54'] : []), '58', '63'].join(',')],
  ]
  for (const [actual, expected] of pairs) {
    if (actual !== expected) throw new Error(`${id}: promptparse reads ${actual}, expected ${expected}`)
  }
}

mkdirSync(OUT, { recursive: true })
for (const c of CASES) {
  const payload = c.build(new ThaiQRPaymentBuilder()).build()
  const expected = expectedFor(c.input)
  verify(c.id, payload, expected)
  const vector = {
    id: c.id,
    scheme: 'promptpay',
    kind: 'valid',
    payload,
    input: c.input,
    expected,
    source: 'thai-qr-payment@1.2.0 ThaiQRPaymentBuilder (MIT) generated; promptparse@1.7.1 parse() (MIT) reads it back to the same fields',
    note: 'Generated by conformance/tools/oracle/gen-promptpay.mjs; tag order checked with promptparse.',
  }
  writeFileSync(join(OUT, `${c.id}.json`), JSON.stringify(vector, null, 2) + '\n')
  console.log(c.id)
}
