// Generate dotnet/src/TingQR.Core/Banks/BankData.g.cs from conformance/banks/ (banks.json, bank-apps.json).
//   node conformance/tools/banks/sync-dotnet.mjs           write the file
//   node conformance/tools/banks/sync-dotnet.mjs --check   exit 1 if the file is stale
// Twin of sync-ts.mjs: same fields, same order (file order: banks by bin, apps by id).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HEADER = '// GENERATED by conformance/tools/banks/sync-dotnet.mjs from conformance/banks/. Do not edit.\n'

const CONFIDENCE = { 'multi-source': 'BankAppConfidence.MultiSource', 'single-source': 'BankAppConfidence.SingleSource' }

// Escaped as \uXXXX: controls, format characters (bidi marks such as U+202A), line and paragraph separators (they
// would end a C# string literal) and lone surrogates. Everything else, Vietnamese and emoji included, stays literal.
const ESCAPE = /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}\p{Cs}]/u
const hex = (unit) => '\\u' + unit.toString(16).toUpperCase().padStart(4, '0')

/** A C# regular string literal for `s`. */
export function csString(s) {
  let out = '"'
  for (const ch of s) {
    if (ch === '"') out += '\\"'
    else if (ch === '\\') out += '\\\\'
    else if (ESCAPE.test(ch)) out += [...Array(ch.length).keys()].map((i) => hex(ch.charCodeAt(i))).join('')
    else out += ch
  }
  return out + '"'
}

const str = (s) => {
  if (typeof s !== 'string') throw new Error(`expected a string, got ${JSON.stringify(s)}`)
  return csString(s)
}
const strOrNull = (s) => (s === null ? 'null' : str(s))

/** Only the fields of the C# `Bank` and `BankApp` records; sources and notes stay in conformance/banks/. */
export function renderBankDataCs(banks, apps) {
  const bank = (b) =>
    `new Bank(Bin: ${str(b.bin)}, Code: ${str(b.code)}, ShortName: ${str(b.shortName)}, Name: ${str(b.name)}, ` +
    `Swift: ${strOrNull(b.swift)}, LogoUrl: ${str(b.logoUrl)})`
  const app = (a) => {
    const confidence = CONFIDENCE[a.confidence]
    if (!confidence) throw new Error(`${a.id}: unknown confidence ${JSON.stringify(a.confidence)}`)
    if (typeof a.vietqrAutofill !== 'boolean') throw new Error(`${a.id}: vietqrAutofill must be a boolean`)
    const ios = a.ios ? `new BankAppIos(Scheme: ${str(a.ios.scheme)})` : 'null'
    const android = a.android
      ? `new BankAppAndroid(Package: ${str(a.android.package)}, Scheme: ${str(a.android.scheme)}, Host: ${str(a.android.host)})`
      : 'null'
    return (
      `new BankApp(Id: ${str(a.id)}, Name: ${str(a.name)}, Bin: ${strOrNull(a.bin)}, Ios: ${ios}, Android: ${android}, ` +
      `Confidence: ${confidence}, VietQrAutofill: ${a.vietqrAutofill})`
    )
  }
  const lines = (items, f) => items.map((x) => `            ${f(x)},\n`).join('')
  return (
    HEADER +
    '#nullable enable\n\n' +
    'namespace TingQR\n{\n' +
    '    internal static class BankData\n    {\n' +
    '        internal static Bank[] Banks() => new Bank[]\n        {\n' +
    lines(banks, bank) +
    '        };\n\n' +
    '        internal static BankApp[] Apps() => new BankApp[]\n        {\n' +
    lines(apps, app) +
    '        };\n    }\n}\n'
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
  const read = (name) => JSON.parse(readFileSync(join(root, 'conformance', 'banks', name), 'utf8'))
  const out = join(root, 'dotnet', 'src', 'TingQR.Core', 'Banks', 'BankData.g.cs')
  const text = renderBankDataCs(read('banks.json').banks, read('bank-apps.json').apps)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(out, 'utf8')
    } catch {}
    if (current !== text) {
      console.error('dotnet/src/TingQR.Core/Banks/BankData.g.cs is stale: run node conformance/tools/banks/sync-dotnet.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  }
}
