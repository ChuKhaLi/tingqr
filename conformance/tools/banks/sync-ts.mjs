// Generate ts/packages/core/src/banks/data.ts from conformance/banks/ (banks.json, bank-apps.json).
//   node conformance/tools/banks/sync-ts.mjs           write the file
//   node conformance/tools/banks/sync-ts.mjs --check   exit 1 if the file is stale
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HEADER = '// GENERATED by conformance/tools/banks/sync-ts.mjs from conformance/banks/. Do not edit.\n'

/** Only the fields of the `Bank` and `BankApp` types; sources and notes stay in conformance/banks/. */
export function renderDataTs(banks, apps) {
  const bank = (b) => ({ bin: b.bin, code: b.code, shortName: b.shortName, name: b.name, swift: b.swift, logoUrl: b.logoUrl })
  const app = (a) => ({
    id: a.id,
    name: a.name,
    bin: a.bin,
    ...(a.ios && { ios: { scheme: a.ios.scheme } }),
    ...(a.android && { android: { package: a.android.package, scheme: a.android.scheme, host: a.android.host } }),
    confidence: a.confidence,
    vietqrAutofill: a.vietqrAutofill,
  })
  const lines = (items, f) => items.map((x) => `  ${JSON.stringify(f(x))},`).join('\n')
  return (
    HEADER +
    "import type { Bank, BankApp } from './types.js'\n\n" +
    `export const BANK_DATA: Bank[] = [\n${lines(banks, bank)}\n]\n\n` +
    `export const BANK_APP_DATA: BankApp[] = [\n${lines(apps, app)}\n]\n`
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
  const read = (name) => JSON.parse(readFileSync(join(root, 'conformance', 'banks', name), 'utf8'))
  const out = join(root, 'ts', 'packages', 'core', 'src', 'banks', 'data.ts')
  const text = renderDataTs(read('banks.json').banks, read('bank-apps.json').apps)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(out, 'utf8')
    } catch {}
    if (current !== text) {
      console.error('src/banks/data.ts is stale: run node conformance/tools/banks/sync-ts.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  }
}
