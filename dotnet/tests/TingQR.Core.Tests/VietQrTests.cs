        [Fact]
        public void AmountAsLongDecimalOrStringGivesTheSameDynamicQr()
        {
            var a = VietQr.Encode(Base(50000L));
            Assert.Equal(a, VietQr.Encode(Base("50000")));
            Assert.Equal(a, VietQr.Encode(Base(50000m)));
            Assert.Equal(a, VietQr.Encode(Base(50000.00m)));
            Assert.Equal(a, VietQr.Encode(Base(50000))); // int converts through long
            Assert.Contains("010212", a);
            Assert.Contains("540550000", a);
        }

