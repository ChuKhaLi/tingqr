        [Fact]
        public void PayloadFormatIndicatorRules()
        {
            var bad = Fail(VietQr.Decode(Rebuild(f => f.Select(x => x.Tag == "00" ? new TlvField("00", "02") : x))));
            Assert.Equal((TingQrErrorCode.InvalidValue, "00"), (bad.Code, bad.Tag));
            var no00 = Fail(VietQr.Decode(Rebuild(f => f.Where(x => x.Tag != "00"))));
            Assert.Equal((TingQrErrorCode.InvalidValue, "00"), (no00.Code, no00.Tag));
            var no01 = Fail(VietQr.Decode(Rebuild(f => f.Where(x => x.Tag != "01"))));
            Assert.Equal((TingQrErrorCode.MissingTag, "01"), (no01.Code, no01.Tag));
            Assert.Equal("Tag 01 (point of initiation) is missing; expected 11 or 12.", no01.Message);
        }

        [Fact]
        public void CrcErrorsPassThroughTrailingNewlineIsAcceptedWithAWarning()
        {
            Assert.Equal(TingQrErrorCode.CrcMismatch, Fail(VietQr.Decode(S.Substring(0, S.Length - 1) + "0")).Code);
            var nl = VietQr.Decode(S + "\n");
            Ok(nl);
            Assert.Equal(new[] { TingQrWarningCode.TrimmedWhitespace }, nl.Warnings.Select(w => w.Code).ToArray());
        }

        [Fact]
        public void DuplicatedTagsAreDuplicateTagInBothModes()
        {
            var dup3801 = WithMerchant(F("00", "A000000727") + F("01", F("00", "970416") + F("01", "257678859") + F("01", "999999999")) + F("02", "QRIBFTTA"));
            var dup3800 = WithMerchant(F("00", "A000000727") + F("00", "A000000727") + F("01", F("00", "970416") + F("01", "257678859")) + F("02", "QRIBFTTA"));
            var dup62 = Rebuild(f => f.Concat(new[] { new TlvField("62", F("08", "A") + F("08", "B")) }));
            foreach (var mode in new[] { ParseMode.Strict, ParseMode.Lenient })
            {
                var a = Fail(VietQr.Decode(dup3801, mode));
                Assert.Equal((TingQrErrorCode.DuplicateTag, "38.01.01"), (a.Code, a.Tag));
                var b = Fail(VietQr.Decode(dup3800, mode));
                Assert.Equal((TingQrErrorCode.DuplicateTag, "38.00"), (b.Code, b.Tag));
                var c = Fail(VietQr.Decode(dup62, mode));
                Assert.Equal((TingQrErrorCode.DuplicateTag, "62.08"), (c.Code, c.Tag));
            }
        }

        [Fact]
        public void MerchantTagsAreReturnedTag62Without08GivesNoPurpose()
        {
            var p = Rebuild(f => f.Concat(new[]
            {
                new TlvField("52", "5812"),
                new TlvField("59", "TINGQR SHOP"),
                new TlvField("60", "HA NOI"),
                new TlvField("62", F("05", "REF123")),
            }));
            var v = Ok(VietQr.Decode(p));
            Assert.Equal("5812", v.MerchantCategoryCode);
            Assert.Equal("TINGQR SHOP", v.MerchantName);
            Assert.Equal("HA NOI", v.MerchantCity);
            Assert.Equal(Dict("05", "REF123"), v.AdditionalData);
            Assert.Null(v.Purpose);
            Assert.Null(v.ExtraFields);
        }

        [Fact]
        public void UninterpretedTopLevelTagsAreReturnedInExtraFields()
        {
            var v = Ok(VietQr.Decode(MomoOld));
            Assert.Equal(Dict("80", "046"), v.ExtraFields);
            Assert.Equal(Dict("05", "MOMOW2W34875080"), v.AdditionalData);
            Assert.Null(Ok(VietQr.Decode(S)).ExtraFields);
            var both = Rebuild(f => f.Concat(new[] { new TlvField("26", F("00", "ZP") + F("01", "X")), new TlvField("80", "046") }));
            Assert.Equal(Dict("26", "0002ZP0101X", "80", "046"), Ok(VietQr.Decode(both)).ExtraFields);
        }

