        [Fact]
        public void MissingTag58StrictFailsLenientDefaultsToVnAndWarns()
        {
            var p = Rebuild(f => f.Where(x => x.Tag != "58"));
            var strict = Fail(VietQr.Decode(p, ParseMode.Strict));
            Assert.Equal((TingQrErrorCode.MissingTag, "58"), (strict.Code, strict.Tag));
            var lenient = VietQr.Decode(p, ParseMode.Lenient);
            Assert.Equal("VN", Ok(lenient).Country);
            Assert.Equal(new[] { (TingQrWarningCode.MissingOptionalTag, "58") }, lenient.Warnings.Select(w => (w.Code, w.Tag!)).ToArray());
        }

        [Fact]
        public void DefaultModeIsLenient()
        {
            var p = Rebuild(f => f.Where(x => x.Tag != "53"));
            var byDefault = VietQr.Decode(p);
            Assert.Equal("704", Ok(byDefault).Currency);
            Assert.Equal(new[] { TingQrWarningCode.MissingOptionalTag }, byDefault.Warnings.Select(w => w.Code).ToArray());
            Assert.False(VietQr.Decode(p, ParseMode.Strict).Ok);
        }

        [Fact]
        public void DifferentGuidOrNoTag38IsUnsupportedScheme()
        {
            var other = Rebuild(f => f.Select(x => x.Tag == "38" ? new TlvField("38", x.Value.Replace("A000000727", "A000000775")) : x));
            Assert.Equal(TingQrErrorCode.UnsupportedScheme, Fail(VietQr.Decode(other)).Code);
            Assert.Equal(TingQrErrorCode.UnsupportedScheme, Fail(VietQr.Decode(Rebuild(f => f.Where(x => x.Tag != "38")))).Code);
            var noGuid = WithMerchant(F("01", F("00", "970416") + F("01", "257678859")) + F("02", "QRIBFTTA"));
            Assert.Equal(TingQrErrorCode.UnsupportedScheme, Fail(VietQr.Decode(noGuid)).Code);
        }

