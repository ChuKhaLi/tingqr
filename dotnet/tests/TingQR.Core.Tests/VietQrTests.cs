        private static VietQrInput Base(QrAmount? amount = null, string? purpose = null, VietQrService service = VietQrService.Account)
            => new VietQrInput { BankBin = "970422", AccountNumber = "0123456789", Amount = amount, Purpose = purpose, Service = service };

        private static TingQrException Thrown(Action a) => Assert.Throws<TingQrException>(a);

        private static string F(string tag, string value) => Tlv.Field(tag, value);

        /// <summary>Rebuild S with fields edited (CRC recomputed).</summary>
        private static string Rebuild(Func<List<TlvField>, IEnumerable<TlvField>> edit)
            => EmvPayloads.Build(edit(Tlv.Parse(S).Where(f => f.Tag != "63").Cast<TlvField>().ToList()));

        private static string WithMerchant(string merchant)
            => Rebuild(f => f.Select(x => x.Tag == "38" ? new TlvField("38", merchant) : x));

        private static IReadOnlyDictionary<string, string> Dict(params string[] pairs)
        {
            var d = new Dictionary<string, string>();
            for (var i = 0; i < pairs.Length; i += 2) d[pairs[i]] = pairs[i + 1];
            return d;
        }

        private static TingQrException Fail(TingQrResult<VietQrData> r)
        {
            Assert.False(r.Ok);
            return r.Error!;
        }

        private static VietQrData Ok(TingQrResult<VietQrData> r)
        {
            Assert.True(r.Ok, r.Error?.Message);
            return r.Value!;
        }

