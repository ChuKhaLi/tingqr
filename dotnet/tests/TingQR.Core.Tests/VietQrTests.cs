        [Theory]
        [MemberData(nameof(RoundTripInputs))]
        public void DecodeOfEncodeGivesTheInputBack(VietQrInput input)
        {
            var v = Ok(VietQr.Decode(VietQr.Encode(input)));
            Assert.Equal(input.BankBin, v.BankBin);
            Assert.Equal(input.AccountNumber, v.AccountNumber);
            Assert.Equal(input.Service, v.Service);
            Assert.Equal(input.Amount?.ToString(), v.Amount);
            Assert.Equal(input.Amount == null ? QrInitiation.Static : QrInitiation.Dynamic, v.Initiation);
            Assert.Equal(input.Purpose, v.Purpose);
            if (input.Purpose != null) Assert.Equal(Dict("08", input.Purpose), v.AdditionalData);
        }

        [Fact]
        public void Tag54IsReturnedVerbatimIncludingDecimals()
        {
            var p = Rebuild(f =>
            {
                var o = f.ToList();
                o.Insert(4, new TlvField("54", "50000.00"));
                o[1] = new TlvField("01", "12");
                return o;
            });
            Assert.Equal("50000.00", Ok(VietQr.Decode(p)).Amount);
