        {
            var e = Fail(VietQr.Decode(null));
            Assert.Equal(TingQrErrorCode.InvalidValue, e.Code);
            Assert.Null(e.Tag);
            Assert.Equal(TingQrErrorCode.InvalidValue, Fail(VietQr.Decode(null, ParseMode.Strict)).Code);
        }

        [Fact]
        public void DecodeEmptyIsFailureNotThrow()
        {
            Assert.False(VietQr.Decode("").Ok);
            Assert.False(VietQr.Decode("", ParseMode.Strict).Ok);
            Assert.False(VietQr.Decode("   ").Ok);
        }

        [Fact]
        public void SameResultUnderTurkishAndGermanCulture()
        {
            // conformance/vectors/vietqr/vietqr-dynamic-amount-purpose.json
            const string payload = "00020101021238540010A00000072701240006970422011001234567890208QRIBFTTA53037045405500005802VN62150811TINGQR TEST6304E922";
            var original = CultureInfo.CurrentCulture;
            try
            {
                string Run(string culture)
                {
                    CultureInfo.CurrentCulture = new CultureInfo(culture);
                    var encoded = new[]
                    {
                        VietQr.Encode(Base("50000", "TINGQR TEST")),
                        VietQr.Encode(Base(50000L, "TINGQR TEST")),
                        VietQr.Encode(Base(50000.00m, "TINGQR TEST")),
                        // lowercase hex CRC exercises the case conversion of the CRC check
                        VietQr.Encode(Base(1234567890123L, "i I")),
                    };
                    var decoded = VietQr.Decode(payload.Substring(0, payload.Length - 4) + "e922");
                    var d = Ok(decoded);
                    return string.Join("|", encoded) + "#" + d.Amount + d.Purpose + d.Currency + d.Country + d.Initiation
                        + string.Join(",", decoded.Warnings.Select(w => w.Code));
                }

                var invariant = Run("");
                Assert.StartsWith(payload + "|" + payload + "|" + payload + "|", invariant);
                Assert.Equal(invariant, Run("tr-TR"));
                Assert.Equal(invariant, Run("de-DE"));
            }
            finally
            {
                CultureInfo.CurrentCulture = original;
            }
        }

